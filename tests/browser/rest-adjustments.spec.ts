import { test, expect } from './app';

test('custom rest and running adjustments survive navigation at 390px and reset on reload', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const epoch = Date.UTC(2026, 10, 6, 18);
  await page.clock.install({ time: epoch });
  await page.goto('/');
  await page.getByRole('button', { name: 'Start workout', exact: true }).click();
  await page.getByLabel('Workout name', { exact: true }).fill('Synthetic custom rest');
  await page.getByRole('button', { name: 'Start workout', exact: true }).click();
  const timer = page.getByRole('region', { name: 'Rest timer', exact: true });
  const remaining = timer.getByLabel('Rest time remaining', { exact: true });
  await expect(remaining).toHaveText('1:30');
  await page.clock.pauseAt(epoch + 60_000);
  await timer.getByLabel('Rest duration', { exact: true }).selectOption('custom');
  await timer.getByLabel('Custom minutes', { exact: true }).fill('0');
  await timer.getByLabel('Custom seconds', { exact: true }).fill('0');
  await expect(timer.getByRole('button', { name: 'Start rest timer', exact: true })).toBeDisabled();
  await expect(timer.getByRole('alert')).toContainText('1 second to 60 minutes');
  await timer.getByLabel('Custom seconds', { exact: true }).fill('20');
  await expect(remaining).toHaveText('0:20');
  await timer.getByRole('button', { name: 'Start rest timer', exact: true }).click();
  await page.clock.fastForward(5_000);
  await timer.getByRole('button', { name: '+15 seconds', exact: true }).click();
  await expect(remaining).toHaveText('0:30');
  await timer.getByRole('button', { name: 'Pause timer', exact: true }).click();
  await expect(timer.getByRole('button', { name: '+15 seconds', exact: true })).toBeDisabled();
  await page.clock.fastForward(60_000);
  await expect(remaining).toHaveText('0:30');
  await timer.getByRole('button', { name: 'Resume timer', exact: true }).click();
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  await page.getByRole('button', { name: 'Workout', exact: true }).click();
  await timer.getByRole('button', { name: '-15 seconds', exact: true }).click();
  await expect(remaining).toHaveText('0:15');
  await timer.getByRole('button', { name: '-15 seconds', exact: true }).click();
  await expect(timer.getByRole('status').filter({ hasText: 'Rest complete.' })).toBeVisible();
  await expect(remaining).toHaveText('0:00');
  await expect(timer.getByRole('button', { name: '+15 seconds', exact: true })).toBeDisabled();
  await timer.getByRole('button', { name: 'Reset timer', exact: true }).click();
  await expect(remaining).toHaveText('0:20');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.reload();
  await expect(remaining).toHaveText('1:30');
  await expect(timer.getByLabel('Rest duration', { exact: true })).toHaveValue('90');
});
