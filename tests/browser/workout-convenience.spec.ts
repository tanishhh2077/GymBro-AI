import { test, expect } from './app';

test('copies previous values, repeats actual sets and starts opt-in rest after saving', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const epoch = Date.UTC(2026, 10, 5, 18);
  await page.clock.install({ time: epoch });
  await page.goto('/');
  await page.getByRole('button', { name: 'Start workout', exact: true }).click();
  await page.getByLabel('Workout name', { exact: true }).fill('Synthetic previous workout');
  await page.getByLabel('Weight unit', { exact: true }).selectOption('kg');
  await page.getByRole('button', { name: 'Start workout', exact: true }).click();
  await page.getByLabel('Exercise name', { exact: true }).fill('Bench press');
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click();
  const exercise = page.getByRole('region', { name: 'Bench press', exact: true });
  await exercise.getByLabel('Reps', { exact: true }).fill('8');
  await exercise.getByLabel('Weight (kg)', { exact: true }).fill('60.5');
  await exercise.getByRole('button', { name: 'Log set', exact: true }).click();
  await expect(exercise.getByRole('row')).toHaveCount(2);
  await exercise.getByLabel('Reps', { exact: true }).fill('6');
  await exercise.getByLabel('Weight (kg)', { exact: true }).fill('65');
  await exercise.getByRole('button', { name: 'Log set', exact: true }).click();
  await expect(exercise.getByRole('row')).toHaveCount(3);
  await page.getByRole('button', { name: 'Finish workout', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Workout saved.' })).toBeVisible();

  await page.getByRole('button', { name: 'Start workout', exact: true }).click();
  await page.getByLabel('Workout name', { exact: true }).fill('Synthetic current workout');
  await page.getByLabel('Weight unit', { exact: true }).selectOption('kg');
  await page.getByRole('button', { name: 'Start workout', exact: true }).click();
  await page.getByLabel('Exercise name', { exact: true }).fill('Bench press');
  await page.getByRole('button', { name: 'Add exercise', exact: true }).click();
  await expect(exercise.getByText('Synthetic previous workout', { exact: false })).toBeVisible();
  const autoRest = page.getByLabel('Start rest automatically after logging a set', { exact: true });
  const remaining = page.getByLabel('Rest time remaining', { exact: true });
  await expect(autoRest).not.toBeChecked();
  await exercise.getByRole('button', { name: 'Use previous set 2 for Bench press', exact: true }).click();
  await expect(exercise.getByLabel('Reps', { exact: true })).toHaveValue('6');
  await expect(exercise.getByLabel('Weight (kg)', { exact: true })).toHaveValue('65');
  await expect(exercise.getByLabel('Reps', { exact: true })).toBeFocused();
  await expect(exercise.getByRole('table')).toHaveCount(0);
  await exercise.getByRole('button', { name: 'Log set', exact: true }).click();
  await expect(exercise.getByRole('row')).toHaveCount(2);
  await expect(exercise.getByLabel('Reps', { exact: true })).toBeFocused();
  await expect(page.getByRole('button', { name: 'Start rest timer', exact: true })).toBeVisible();

  await page.clock.pauseAt(epoch + 60_000);
  await page.getByLabel('Rest duration', { exact: true }).selectOption('30');
  await autoRest.check();
  await exercise.getByRole('button', { name: 'Repeat last set for Bench press', exact: true }).click();
  await expect(exercise.getByRole('row')).toHaveCount(3);
  await expect(remaining).toHaveText('0:30');
  await page.clock.fastForward(5_000);
  await expect(remaining).toHaveText('0:25');
  await page.getByRole('button', { name: 'Edit set 1 for Bench press', exact: true }).click();
  await exercise.getByLabel('Reps', { exact: true }).fill('9');
  await exercise.getByRole('button', { name: 'Save set', exact: true }).click();
  await expect(exercise.getByRole('cell', { name: '9', exact: true })).toBeVisible();
  await expect(remaining).toHaveText('0:25');
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  await page.getByRole('button', { name: 'Workout', exact: true }).click();
  await expect(autoRest).toBeChecked();
  await expect(remaining).toHaveText('0:25');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.reload();
  await expect(autoRest).not.toBeChecked();
  await expect(remaining).toHaveText('1:30');
  await page.getByRole('button', { name: 'Resume workout', exact: true }).click();
  await expect(exercise.getByRole('row')).toHaveCount(3);
  await expect(exercise.getByRole('cell', { name: '9', exact: true })).toBeVisible();
});
